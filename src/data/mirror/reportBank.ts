const jong = (w: string) => { const c = w.charCodeAt(w.length - 1) - 0xac00; return c >= 0 && c <= 11171 ? c % 28 : -1; };
/**
 * 「~거예요」 끝맺음을 다른 낮춤 말로(엔진이 한 보고서의 「거예요」를 3분의 1 이하 · 연달음 0으로 맞출 때 쓴다).
 *  「~쪽/편/사람/역할/사이/모습일 거예요」 → 「~으로 보여요」 · 「~인 듯해요」 · 「~일지도 몰라요」 · 「~일 가능성이 커요」(편은 「편이에요」도 — 문장 앞에 숫자 근거가 있다)
 *  「~ㄹ 거예요」 → 「~ㄹ지도 몰라요」 · 「~ㄹ 듯해요」 · 「~ㄹ 가능성이 커요」,  「~ㄴ 거예요」 → 「~ㄴ 셈이에요」.
 */
export function softEndings(t: string): string[] {
  const m = t.match(/^([\s\S]*?)(\S+) 거예요\.$/);
  if (!m) return [];
  const [, pre, w] = m;
  const nm = w.match(/^(.*?)(쪽|편|사람|역할|사이|모습)일$/);
  if (nm) {
    const noun = nm[1] + nm[2], ro = `${noun}${batchim(noun) && jong(noun) !== 8 ? "으로" : "로"}`;
    return [`${pre}${ro} 보여요.`, `${pre}${noun}인 듯해요.`, `${pre}${noun}일지도 몰라요.`, `${pre}${noun}일 가능성이 커요.`, ...(nm[2] === "편" ? [`${pre}${noun}이에요.`] : [])];
  }
  if (jong(w) === 8) return [`${pre}${w}지도 몰라요.`, `${pre}${w} 듯해요.`, `${pre}${w} 가능성이 커요.`];
  if (jong(w) === 4) return [`${pre}${w} 셈이에요.`];
  return [];
}


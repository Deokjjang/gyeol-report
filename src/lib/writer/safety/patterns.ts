/**
 * 문체 금지 패턴(P3 A-3). 지식 lint·Fusion 패치 검사·안전망이 같은 정규식을 쓴다.
 * - OLD_NEGATIVE: 옛 해석의 부정 낱말. "옛날에는 흉으로 읽었지만"처럼 부정하는 문장 안에서도 금지(불안 단어를 꺼내지 않는다).
 *   제외: 불길(불꽃), 흉내·흉터·흉보다, 결과부터(과부), 망신살(신살 이름).
 *   옛 해석을 꺼내 부정하는 면책 문장("겁주는 옛 풀이가 있지만", "~라는 예언이 아닙니다")도 같은 이유로 금지.
 * - PAST_ASSERT: 과거 경험 평서 단정. 과거는 질문형("~한 적 있지 않나요?")이나 경향형("~하는 편입니다")으로만 쓴다.
 */
export const OLD_NEGATIVE = /길흉|흉(하|한|함|해|으로|이라|살|신|운|사|조|성|명|일|작)|흉(?=[\s.,)(]|$)|액운|액땜|횡액|액살|불길(하|한|함|해)|재앙|재난|박복|단명|요절|횡사|화근|악운|불운|팔자가 ?(세|사납)|(?<![가-힣])과부|홀아비|극처|극부|패가망신|옛 풀이|옛 이름|겁(을 ?주|주는)|이름이 무섭|예언이 아닙|예언으로 읽|부부 불화|미워하는 사이|벌을 받는 글자/;

export const PAST_ASSERT = /겪어 ?(봤|왔)(습니다|어요|죠|을 (겁니다|거예요))|겪어 본 (사람이라|감각이라|만큼)|한 적이 (있었|많았|있습니다|있어요|있을 (겁니다|거예요))|했었(습니다|어요|죠)|(어릴 때|어렸을 때|어린 시절|학창 시절|예전에|그동안)[^.?!]{0,40}(했|였|었|났)(습니다|어요|죠|을 (겁니다|거예요))/;

/** 문장 단위로 자른다(마침표·물음표·느낌표·줄바꿈). */
export function splitSentences(text: string): string[] {
  return text.match(/[^.!?\n]+[.!?]+["'”’)]*|[^.!?\n]+$/gm)?.map(s => s.trim()).filter(Boolean) ?? [];
}

/** 과거 단정: 물음표로 끝나는 문장(질문형)과 따옴표 안 대사는 허용. */
export function isPastAssertion(sentence: string): boolean {
  const s = sentence.trim().replace(/'[^']*'|"[^"]*"|‘[^’]*’|“[^”]*”/g, "");
  return PAST_ASSERT.test(s) && !/\?["'”’)]*$/.test(sentence.trim());
}

export const PAST_ASSERT = /겪어 ?(봤|왔)(습니다|어요|죠|을 (겁니다|거예요))|겪어 본 (사람이라|감각이라|만큼)|한 적이 (있었|많았|있습니다|있어요|있을 (겁니다|거예요))|했었(습니다|어요|죠)|(어릴 때|어렸을 때|어린 시절|학창 시절|예전에|그동안)[^.?!]{0,40}(했|였|었|났)(습니다|어요|죠|을 (겁니다|거예요))/;

/**
 * 경험 단정(P3.5 A5): 고객이 무언가를 겪었다고 전제하는 꼴("~해 본 사람", "~을 겪어 본", "~했던 사람", "~본 적이 있습니다").
 * 경향형("~하는 편입니다")이나 질문형("~해 본 적 있지 않나요?")으로 쓴다. lint·안전망 경고가 isPastAssertion으로 함께 본다.
 */
export const EXPERIENCE_ASSERT = /(해|겪어|받아|느껴|당해|가|와|써|만나|들어|잃어|견뎌|버텨|살아) ?본 (사람|분|당신|감각|만큼|경험)|겪어 ?(본|봤|왔)|[가-힣]했던 (사람|분|당신)|본 적이 (있|많)(습니다|어요|죠|을 거예요|을 겁니다)|적이 (있는|많은) (사람|분|당신)/;

/**
 * 경험 단정 잔여(P3.6 A6): "~하는 요령이 늘어난 것도", "~해 본 일이", "~해 왔습니다"처럼 지난 경험을 평서문으로 전제하는 꼴.
 * "안 해 본 일"처럼 부정하는 꼴은 경험 단정이 아니다. 안전망은 softenExperience로 경향형·질문형으로 바꿀 수 있으면 바꾸고, 아니면 지운다(메타에 기록).
 */
export const EXPERIENCE_RESIDUE = /요령이 (늘었|늘어난|늘어|붙었|생겼)|(익숙해|능숙해|노련해|단단해)진 (것도|것은|덕분|이유)|(?<!(?:안|못) )(해|가|와|써|만나|들어|받아|느껴|겪어|버텨|견뎌|살아|지켜|챙겨|맡아|해내|이겨|넘어|도와|기다려|참아|배워|모아|아껴|미뤄|부딪쳐) ?본 (일|날|기억|덕분|덕|자리|길|시간)(이|을|은|도|에|으로)|(챙겨|버텨|견뎌|지켜|살아|맡아|참아|모아|쌓아|해) 왔(습니다|어요|죠|을 (겁니다|거예요))/;

/** 경험 단정을 안전하게 경향형·질문형으로 바꾼다. 바꿀 수 없으면 null(안전망이 지운다). */
export function softenExperience(sentence: string): string | null {
  const out = sentence
    .replace(/요령이 늘어난 것/g, "요령이 잘 붙는 것")
    .replace(/요령이 늘었습니다/g, "요령이 잘 붙는 편입니다").replace(/요령이 늘었어요/g, "요령이 잘 붙는 편이에요")
    .replace(/(익숙해|능숙해|노련해|단단해)진 (것도|것은)/g, "$1지는 $2")
    .replace(/([가-힣]) ?본 (사람|분|당신)/g, "$1 보는 $2")
    .replace(/([가-힣])했던 (사람|분|당신)/g, "$1하는 $2")
    .replace(/본 적이 (있|많)(습니다|어요|죠|을 거예요|을 겁니다)[.!]?$/, "본 적 $1지 않나요?");
  return out !== sentence && !isPastAssertion(out) ? out : null;
}

/** 문장 단위로 자른다(마침표·물음표·느낌표·줄바꿈). */
export function splitSentences(text: string): string[] {
  return text.match(/[^.!?\n]+[.!?]+["'”’)]*|[^.!?\n]+$/gm)?.map(s => s.trim()).filter(Boolean) ?? [];
}

/** 과거·경험 단정: 물음표로 끝나는 문장(질문형)과 따옴표 안 대사는 허용. */
export function isPastAssertion(sentence: string): boolean {
  const s = sentence.trim().replace(/'[^']*'|"[^"]*"|‘[^’]*’|“[^”]*”/g, "");
  return (PAST_ASSERT.test(s) || EXPERIENCE_ASSERT.test(s) || EXPERIENCE_RESIDUE.test(s)) && !/\?["'”’)]*$/.test(sentence.trim());
}

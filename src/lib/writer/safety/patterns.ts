/**
 * 표기 정리(P6b E-9, C-3): 마크다운 강조 기호, 같은 이름 겹쳐 쓰기("정축·정축(丁丑)", "정축(정축)"), 금지 문형("~장면이에요"→"~식이에요").
 * 뜻을 바꾸지 않는 결정론 치환만 한다.
 */
export function tidyText(p: string): string {
  return p.replace(/\*\*|__/g, "")
    .replace(/(?<![가-힣])([가-힣]{2,5})·\1(?=\()/g, "$1")
    .replace(/(?<![가-힣])([가-힣]{2,5})\(\1\)/g, "$1")
    .replace(/(는|은|ㄴ|던) 장면이에요/g, "$1 식이에요").replace(/(는|은|던) 장면입니다/g, "$1 식입니다")
    .replace(/장면이 어울(립니다|려요)/g, "모습이 어울$1");
}
/** 금지 소제목 머리(P6b C-3): "앞에서 본 ~"으로 시작하는 소제목은 그 머리를 뗀다. */
export const tidyHeading = (h: string) => h.replace(/\*\*|__/g, "").replace(/^(앞에서|앞서|앞 장에서) (본|말한|나온) /, "").trim();

/** 비유 표지(P6b B-5): 장당 비유 수 지표·뜻 문장 검사. "같이"(함께)·"같은 날" 같은 일상어는 뺀다. */
export const SIMILE = /처럼|마치|(?<![가-힣])듯(이|한)?(?![가-힣])|같은 (사람|기운|힘|자리|그림|모습|구조|나무|물|불|흙|쇠|해|달|날씨|계절)(이|을|입|예|으로|처럼)?/;
/** 문장 안 비유 표지 수. */
export const simileCount = (text: string) => text.match(new RegExp(SIMILE.source, "g"))?.length ?? 0;

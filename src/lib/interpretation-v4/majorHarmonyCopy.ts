import type { TenGod } from "../report-knowledge/annualFortuneTypes";
import { particle as p } from "./copyRealizer";

/** Copy only: invoked after the existing cycle/natal relation selector finds harmony.
 * A connection is not automatically a helper star, a new job or a guaranteed event. */
export function majorHarmonyCopy(god: TenGod, topic: string, scene: string, mature: boolean, past: boolean) {
  const o = p(topic, "을", "를"), t = p(topic, "은", "는");
  const first: Record<TenGod, string> = {
    비견: `혼자 골라도 되는 ${topic}, 남의 이야기를 듣고 정해도 내 선택인 것은 같습니다. ${scene}에서 만난 상대가 ${o} 다른 각도로 보여주면 선택의 폭도 넓어집니다.`,
    겁재: `서로 다른 솜씨를 ${topic}에 보탠다면 혼자 못 하던 것까지 해볼 여지가 있습니다. ${scene}에서 상대가 끝낸 부분을 보면 이 만남이 경쟁만은 아니라는 든든함도 생깁니다.`,
    식신: `${o} 보고 자기 경험을 보태주는 사람이 반갑습니다. ${scene}에서 받은 구체적인 반응은 막연한 칭찬보다 다음에 만들어볼 재미를 더해줍니다.`,
    상관: `${o} 바꾸자는 말에 ‘나도 그게 불편했어’라고 답하는 사람이 있을 만합니다. ${scene}에서는 혼자 까다롭다는 기분보다 같이 고쳐볼 편이 있다는 힘이 살아납니다.`,
    편재: `${o} 알려준 인연이 다른 경험까지 연결할 수 있습니다. ${scene}에서 만난 사람에게 ${o} 어떻게 써보고 싶은지 듣는 대화도 남을 만합니다.`,
    정재: `${o} 오래 지키려면 가까운 사람과 원하는 생활도 나눌 만합니다. ${scene}에서 함께 고른 ${topic}에는 절약뿐 아니라 같이 누릴 즐거움도 담깁니다.`,
    편관: `${o} 혼자 감당하는 모습만이 강한 것은 아닙니다. ${scene}에서 놓친 조건을 짚어주는 사람이 있다면 ${o} 정한 뒤의 부담도 나눌 여지가 있습니다.`,
    정관: `${o} 지켜온 모습을 알아보는 사람이 관계의 든든한 바탕입니다. ${scene}에서 말없이 보탠 수고를 기억한다면 ${topic}에도 믿고 맡길 여유가 생깁니다.`,
    편인: `${o} 다른 시선으로 보는 사람과 이야기를 이어갈 만합니다. ${scene}에서 당연하게 여겼던 ${o} 상대가 되물으면 질문에도 새 입구가 생깁니다.`,
    정인: `${o} 알려주는 사람의 설명에는 경험한 순서가 담겨 있습니다. ${scene}에서 모른다고 말할 수 있다면 ${o} 익히는 시간도 덜 외롭습니다.`,
  };
  const later: Record<TenGod, string> = {
    비견: `${t} 이제 혼자만의 취향을 넘어 함께 쓸 기준이 될 수 있습니다. ${scene}에서 상대의 선택도 나란히 놓아보면 내 방식이 어디까지 통하는지 더 넓게 보입니다.`,
    겁재: `다시 연락하고 싶은 사람이 ${topic} 끝에 남는다면 그것도 얻은 것입니다. ${scene}에서 서로의 수고를 기억하는 태도가 다음 시작을 덜 외롭게 만듭니다.`,
    식신: `${o} 받아본 사람이 다른 쓰임을 알려주면 만든 보람이 커집니다. ${scene}에서 내 손을 떠난 뒤에도 도움이 되는 모습을 보는 재미가 있습니다.`,
    상관: `${o} 두고 다른 의견을 내던 사람과도 새 답을 만들 수 있습니다. ${scene}에서 누구 말이 맞았는지보다 무엇이 편해졌는지 함께 보는 관계가 어울립니다.`,
    편재: `${o} 넓히는 데 서로 다른 경험이 좋은 밑천입니다. ${scene}에서 작은 약속을 지켜본 사이면 ${o} 함께 다루는 마음도 든든해집니다.`,
    정재: `${o} 나눠 이야기할 수 있으면 돈의 기준도 덜 외로운 선택이 됩니다. ${scene}에서 같은 금액보다 같은 생활을 원한다는 점을 발견할 여지가 있습니다.`,
    편관: `늘 찬성만 하기보다 ${topic}에 숨은 부담도 말해주는 사람이 반갑습니다. ${scene}에서 의견이 달랐어도 ${o} 함께 책임진다는 신뢰는 남을 수 있습니다.`,
    정관: `${o} 함께 지켜온 사람에게는 짧은 말로도 전해지는 믿음이 있습니다. ${scene}에서 서로의 어려운 사정을 일찍 알면 약속을 포기하기 전에 나눌 방법도 생깁니다.`,
    편인: `${o} 전혀 다른 분야의 사람에게 설명하다 뜻밖의 연결을 찾을 수 있습니다. ${scene}에서 쉬운 말로 되묻는 질문이 내 생각의 빈 곳을 채워줍니다.`,
    정인: `${o} 배웠던 자리에서 이제는 내 경험을 보탤 차례도 생깁니다. ${scene}에서 상대가 혼자 해내는 모습을 보면 도움을 주고받는 관계의 보람이 선명해집니다.`,
  };
  const text = (mature ? later : first)[god];
  return past ? `${p(topic, "과", "와")} 맞물렸던 인연을 지금의 장면에 비춰 돌아볼 만합니다: ${text}` : text;
}

export function selectCareerVoice(state: NarrativeState) {
  const order = ["decisive", "precise", "creative", "inquiry", "challenger", "field", "meaning"];
  for (const id of order) {
    const voice = CAREER_VOICES[id];
    const fusions = state.packet.fusions.filter(f => voice.rules.includes(f.ruleId) && f.strength === "strong");
    if (fusions.length) return { id, ...voice, proof: proof([], [], fusions, [`v4:career-voice:${id}`]) };
  }
  const seed = (role: string) => state.pillar.material.seeds.find(s => s.role === role) ?? state.master.material.seeds.find(s => s.role === role)!;
  const source = proof([state.pillar, state.master], [seed("character"), seed("inside"), seed("strength"), seed("work"), seed("money"), seed("shadow"), seed("ending")], [], ["v4:career-voice:natal"]);
  return { id: "natal", rules: [], headline: seed("work").text.replace(/\.$/, ""),
    opening: `${seed("character").text} ${seed("inside").text}`, strengthTitle: "직함이 없어도 없어지지 않는 내 힘", strength: seed("strength").text,
    reaction: seed("work").text, money: seed("money").text,
    independence: `${seed("relationships").text} 내 일을 고를 때도 어떤 사람과 어떤 약속으로 움직이는지가 중요합니다. 소속이 있든 독립하든 그 기준이 지켜지는 곳에서 힘을 써볼 수 있습니다.`,
    shadow: seed("shadow").text, direction: `${state.master.material.seeds.find(s => s.role === "inside")!.text} 다음 일에서는 그 감각이 실제로 쓰일 하루를 상상해볼 만합니다. 이름만 멋진 자리보다 해낸 일이 나를 더 믿게 만드는 경험이 좋은 출발점입니다.`,
    final: state.master.feature === "day_master_jeonghwa" ? "당신이 더한 작은 차이가, 다음에도 당신을 찾을 이유가 됩니다." : seed("ending").text, workingPhrase: "내 방식으로 맡은 일을 이어가는 힘", proof: source };
}

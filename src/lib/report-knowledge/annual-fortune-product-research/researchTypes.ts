/** Offline research types. Stable research IDs cannot be calculated Evidence IDs. */
export type ResearchId = `afpr:${string}`;
declare const actualEvidenceBrand: unique symbol;
export type ExistingEvidenceId = string & { readonly [actualEvidenceBrand]: true };
export type Offline = {
  readonly id: ResearchId;
  readonly productKey: "annual_fortune";
  readonly connectedToRuntime: false;
  readonly approvedForCustomer: false;
  readonly existingScoreContribution: false;
  readonly runtimeEvidenceIds: readonly [];
};
export type Locator = {
  readonly file: string;
  readonly exportName: string;
  readonly index: number;
  readonly originalId: string;
  readonly sourceVersion: string;
  readonly recordSha256: string;
};
export type Study = Offline & {
  readonly scope: string;
  readonly meaning: string;
  readonly positive: string;
  readonly risk: string;
  readonly twist: string;
  readonly action: string;
  readonly scene: { readonly text: string; readonly hypothetical: true; readonly isCustomerHistory: false };
  readonly counterexample: string;
  readonly requires: readonly string[];
  readonly disallowed: readonly string[];
  readonly sourceRefs: readonly string[];
  readonly verification: string;
  readonly [field: string]: unknown;
};
export type Source = Offline & {
  readonly key: string;
  readonly verification: string;
  readonly limitation: string;
  readonly file?: string | null;
  readonly fileSha256?: string | null;
  readonly symbol?: string;
  readonly sourceVersion?: string;
  readonly url?: string;
  readonly title?: string;
  readonly principle?: string;
  readonly checkedOn?: string;
  readonly modernApplicationSource?: string;
};
export type Crosswalk = Offline & {
  readonly locator: Locator;
  readonly originalState: Readonly<Record<string, unknown>>;
  readonly referenceOnly: true;
  readonly applicationPolicy: string;
  readonly bindingImplemented: false;
  readonly applicationLocator?: unknown;
  readonly temporalFactSource?: false;
};
export type MbtiStudy = Offline & {
  readonly type: string;
  readonly scope: "personal_only";
  readonly referenceOnly: true;
  readonly locators: readonly {
    readonly locator: Locator;
    readonly basis: unknown;
    readonly domain: string;
    readonly sourceRefs: readonly string[];
    readonly applicationGate: string;
    readonly provenance: string;
  }[];
  readonly applicationPolicy: string;
  readonly unknownPolicy: string;
  readonly pairPolicy: string;
  readonly bindingImplemented: false;
};
export type Binding = Offline & {
  readonly scope: "future_binding_design";
  readonly stage: string;
  readonly meaning: string;
  readonly input: string;
  readonly output: string;
  readonly checks: string;
  readonly forbidden: string;
  readonly sourceRefs: readonly string[];
  readonly implemented: false;
  readonly ownerContract: string;
  readonly periodContract: string;
  readonly certaintyContract: string;
  readonly sourceAncestryContract: string;
  readonly sourceVersionContract: string;
  readonly failureReasons: readonly string[];
  readonly duplicatePolicy: string;
  readonly counterexamples: readonly string[];
  readonly approvalConditions: readonly string[];
  readonly missingPolicy: string;
  readonly approval: string;
};
export type Rejected = Offline & {
  readonly claim: string;
  readonly reason: string;
  readonly review: "rejected_or_withheld";
  readonly sourceRefs: readonly string[];
  readonly approved: false;
};
export type ObservedView = Offline & {
  readonly caseId: string;
  readonly month: number;
  readonly selectedYear: number;
  readonly scope: "actual_offline_month_observation";
  readonly sourceObservation: { readonly file: string; readonly caseId: string; readonly month: number; readonly recordSha256: string };
  readonly actualFocus: unknown;
  readonly segmentCount: number;
  readonly originalFactIds: readonly string[];
  readonly displayedProofSourceRefs: readonly string[];
  readonly researchQuestion: string;
  readonly referenceOnly: true;
  readonly notNewMeaningOrEvidence: true;
  readonly applicationPolicy: string;
  readonly bindingImplemented: false;
};
export type FutureBinding = {
  readonly researchId: ResearchId;
  readonly evidenceIds: readonly ExistingEvidenceId[];
  readonly personOwner: string;
  readonly natalPosition: string | null;
  readonly referenceStem: string;
  readonly targetStemOrBranch: string;
  readonly effectiveAnnualPillar: string;
  readonly monthlyPillar: string;
  readonly activeDayun: { readonly state: "active" | "before_first_cycle" | "transition_uncertain"; readonly cycleIds: readonly string[] };
  readonly window: { readonly startInclusive: string; readonly endExclusive: string };
  readonly certainty: "confirmed" | "conditional" | "unknown";
  readonly sourceIds: readonly string[];
  readonly sourceVersions: readonly string[];
  readonly sourceAncestry: readonly string[];
  readonly conditions: readonly string[];
  readonly counterexamples: readonly string[];
  readonly failures: readonly string[];
  readonly factRoots: readonly { readonly id: string; readonly scope: string; readonly periodKey: string }[];
  readonly informationFunction: "new_fact" | "new_application" | "comparison" | "continuity" | "withhold";
  readonly compositeVerdict: "unsupported";
  readonly approvedForCustomer: false;
  readonly implemented: false;
};

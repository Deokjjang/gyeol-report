/** final·final2 판독 인용(tools/final/stored-check.ts·tools/final2/stored-check.ts QUOTES). */
export function knownPrev(): Known[] {
  const rows = JSON.parse(readFileSync("tools/final3/known-prev.json", "utf8")) as { src: "final" | "final2"; item: string; book: string; quote: string; how: string; rule: string; label: string }[];
  const cat = (r: (typeof rows)[number]): Cat => {
    const x = `${r.rule} ${r.label}`;
    if (/guide_copy|internal_term|notice_repeat|지어낸 연차|상태가 대표|말하는 것이 아니라|정해 주는 것은 아닙|말하는 건 아닙/.test(x)) return "L";
    if (/orphan_start|awkward|되려|기억\(Si\)|편인\(偏人\)|매우 신약 →|충 축미충/.test(x)) return "A";
    if (/기준으로 썼어요|가을 남은|토 과다/.test(x)) return "T";
    if (r.item === "1-1") return "R";
    if (r.item === "1-3") return "C";
    return "F";
  };
  return rows.map((r, i) => ({ id: `${r.src}-${i + 1}`, src: r.src, book: r.book, cat: cat(r), re: new RegExp(r.quote), label: r.label, layer: r.how === "cover" ? "cover" : r.how === "render" ? "render" : "sentence" }));
}

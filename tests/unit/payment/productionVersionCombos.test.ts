import { PGlite } from "@electric-sql/pglite";
import { readFileSync, readdirSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from "vitest";
vi.mock("server-only", () => ({}));
import { confirmPaidReport, readPublishedReport } from "../../../src/lib/payment/paidReportReliability";
import type { ReliabilityResult, ReliabilityStore } from "../../../src/lib/payment/paidReportReliabilityStore";
import { storedBook, validateBookPublication } from "../../../src/lib/book/storedReport";

// The 9 (productType, productVersion) combinations seen in production paid_report_snapshots (2026-10-28),
// all gate_version paid-report-v1. Legacy v1/1.0/v2 carry calendarVersion/calendarCalculationVersion
// saju-calendar-kst-v2; v4 has no top-level calendar fields. Fixtures are fictional dev personas generated by
// Phase 0 code (463c4f8e, kst-v2 engine) with docs/v5/p01-fixture-generator.ts.txt. This file must pass on
// both Release 1 (Phase 0) and Release 2 code.
const COMBOS = [
  ["annual_fortune", "v4"], ["career_money_study", "v1"], ["career_money_study", "v4"], ["love_marriage_child", "v4"],
  ["major_fortune", "v4"], ["saju_mbti_compatibility", "1.0"], ["saju_mbti_compatibility", "v4"], ["saju_mbti_full", "v2"], ["saju_mbti_full", "v4"],
] as const;
const load = (product: string, version: string): Record<string, unknown> =>
  JSON.parse(gunzipSync(readFileSync(`tests/fixtures/production-version-combos/${product}-${version}.json.gz`)).toString("utf8"));
const UNKNOWN = "saju-calendar-v9-test";

describe("production version combinations", () => {
  it.each(COMBOS)("%s %s matches the production shape", (product, version) => {
    const snapshot = load(product, version);
    const evidence = snapshot.evidencePacket as Record<string, unknown>;
    expect([snapshot.productType, snapshot.productVersion, (snapshot.draft as Record<string, unknown>).productVersion]).toEqual([product, version, version]);
    const calendar = version === "v4" ? undefined : "saju-calendar-kst-v2";
    expect([snapshot.calendarVersion, snapshot.calendarCalculationVersion, evidence.calendarVersion, evidence.calendarCalculationVersion])
      .toEqual([calendar, calendar, calendar, calendar]);
  });

  it.each(COMBOS)("%s %s passes the read gate without quarantine", async (product, version) => {
    const snapshot = load(product, version);
    const call = vi.fn(async (action: string) => action === "read_report" ? { ok: true, status: "COMPLETED", snapshot } : { ok: true });
    const read = await readPublishedReport({ call } as ReliabilityStore, String(snapshot.reportId), validateBookPublication);
    expect(read).toMatchObject({ ok: true, status: "COMPLETED" });
    expect(read.snapshot).toEqual(snapshot);
    expect(call.mock.calls.map(([action]) => action)).toEqual(["read_report"]);
    if (version === "v4") expect(storedBook(snapshot)).not.toBeNull();
  });
});

// Actual SQL (all migrations + the production reconcile), without the quarantine recovery patch:
// there, quarantine clears snapshot_json, so an unknown version must never reach quarantine.
describe("production version combinations on the actual SQL", () => {
  let db: PGlite;
  let store: ReliabilityStore;
  let sequence = 0;
  const log = vi.spyOn(console, "error").mockImplementation(() => {});
  beforeAll(async () => {
    db = new PGlite();
    await db.exec("create role anon; create role authenticated; create role service_role;");
    for (const file of readdirSync("supabase/migrations").filter((name) => /^\d{4}_.*\.sql$/u.test(name)).sort()) {
      await db.exec(readFileSync(`supabase/migrations/${file}`, "utf8").replace(/^﻿/u, ""));
    }
    await db.exec(readFileSync("supabase/migrations/20260920163924_production_reliability_reconcile.sql", "utf8"));
    store = { async call(action, data = {}) {
      const result = await db.query<{ value: ReliabilityResult }>("select public.paid_report_reliability($1,$2::jsonb) as value", [action, JSON.stringify(data)]);
      return result.rows[0].value;
    } };
  }, 30000);
  afterAll(async () => { log.mockRestore(); await db?.close(); });
  afterEach(() => log.mockClear());

  async function published(snapshot: Record<string, unknown>) {
    const orderId = `order-${++sequence}`;
    expect(await store.call("create_order", { paymentOrderId: `po-${sequence}`, providerOrderId: orderId, productType: snapshot.productType, provider: "toss", amount: 1290, inputSnapshot: { reportInputPayload: { productKey: snapshot.productType } } })).toMatchObject({ ok: true });
    const confirmed = await confirmPaidReport({ orderId, paymentKey: `key-${sequence}`, amount: 1290 }, store, async () =>
      ({ ok: true as const, confirm: { provider: "toss" as const, paymentKeyReceived: true as const, orderId, amount: 1290, status: "DONE" } }));
    const reportId = String(confirmed.reportId);
    const stored = { ...snapshot, reportId };
    await db.query("update paid_report_snapshots set status='COMPLETED', snapshot_json=$2::jsonb, gate_version='paid-report-v1', published_at=now() where report_id=$1", [reportId, JSON.stringify(stored)]);
    return { reportId, stored };
  }
  const row = async (reportId: string) => (await db.query<{ status: string; snapshot_json: unknown; gate_version: string }>(
    "select status, snapshot_json, gate_version from paid_report_snapshots where report_id=$1", [reportId])).rows[0];

  it.each(COMBOS)("%s %s opens and stays stored", async (product, version) => {
    const { reportId, stored } = await published(load(product, version));
    const read = await readPublishedReport(store, reportId, validateBookPublication);
    expect(read).toMatchObject({ ok: true, status: "COMPLETED" });
    expect(read.snapshot).toEqual(stored);
    expect(await row(reportId)).toEqual({ status: "COMPLETED", snapshot_json: stored, gate_version: "paid-report-v1" });
    expect(log).not.toHaveBeenCalled();
  });

  it.each(COMBOS)("%s %s with an unknown calendar version keeps snapshot_json", async (product, version) => {
    const snapshot = JSON.parse(JSON.stringify(load(product, version)).replaceAll("saju-calendar-kst-v2", UNKNOWN)) as Record<string, unknown>;
    const { reportId, stored } = await published(snapshot);
    const read = await readPublishedReport(store, reportId, validateBookPublication);
    expect(read).toEqual({ ok: true, status: "FAILED_REQUIRES_ATTENTION", code: "UNKNOWN_CALCULATION_VERSION", snapshot: null });
    expect(log).toHaveBeenCalledWith(JSON.stringify({ event: "REPORT_READ_UNKNOWN_CALCULATION_VERSION", reportId, versions: [UNKNOWN] }));
    expect(await row(reportId)).toEqual({ status: "COMPLETED", snapshot_json: stored, gate_version: "paid-report-v1" });
  });
});
